def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
    db = Database("data/bot.db")

    written = 0
    skipped = 0
    for berman_number, (statement, solution, answer) in sorted(SOLUTIONS.items()):
        p = db.get_problem_by_berman_number(berman_number)
        if p is None:
            log.warning("№%d: not in DB, skip", berman_number)
            continue
        if p.has_solution and not OVERWRITE:
            log.info("№%d: already has solution, skip", berman_number)
            skipped += 1
            continue
        # Update; pass through existing values unless we override.
        new_statement = statement if statement is not None else p.statement_html
        db.update_problem_html(
            berman_number=berman_number,
            statement_html=new_statement,
            solution_html=solution,
            answer_html=answer,
        )
        # Force re-render by clearing image_path (empty string is treated as missing).
        db.update_image_path(p.id, "")
        log.info("№%d: solution written", berman_number)
        written += 1

    log.info("Written: %d, skipped: %d, total: %d", written, skipped, len(SOLUTIONS))
    return 0


